/** Browser locale tags map to the two supported interface languages. */
export function normalizeLocale(value: unknown): Locale {
  return typeof value === "string" && /^zh(?:[-_]|$)/i.test(value.trim()) ? "zh" : "en";
}

/** Plain strings only: React remains responsible for escaping rendered values. */
export function translate(locale: Locale, english: string, values: Record<string, string | number> = {}): string {
  const template = locale === "zh" && Object.hasOwn(ZH_MESSAGES, english) ? ZH_MESSAGES[english] : english;
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (token, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : token);
}

/** Stable English keys let a locale switch update an existing error without another request. */
export function searchErrorKey(code: unknown): string {
  switch (code) {
    case "QUERY_TOO_LARGE": case "REQUEST_TOO_LARGE": return "Please shorten the search request.";
    case "TAXONOMY_MISMATCH": return "The search vocabulary changed. Reload and try again.";
    case "INVALID_REQUEST": return "Please describe your request in the search form.";
    case "INVALID_INTERPRETATION": case "INVALID_RESPONSE": case "INCOMPLETE_RESPONSE": case "MODEL_REFUSAL":
      return "The AI response could not be validated.";
    case "duplicate_request": return "This request was already submitted. Edit criteria manually, or make a new explicit search.";
    case "client_limit": return "This preview's per-visitor search allowance is temporarily used up. Please explore or edit criteria manually, then try later.";
    case "daily_limit": case "trial_exhausted": case "quota_unavailable":
      return "Live AI is temporarily unavailable under this preview's usage allowance. Browsing and editable criteria still work.";
    case "PROVIDER_TIMEOUT": return "The AI service did not answer in time. Your criteria can still be edited manually.";
    case "PROVIDER_RATE_LIMIT": return "The AI service is busy. Please try later or use the editable criteria.";
    default: return "AI search is unavailable right now. You can still build a shortlist with the editable criteria below.";
  }
}

